export const AGO_FNS = {
  en: (d) =>
    d === 0
      ? 'today'
      : d === 1
        ? '1 day ago'
        : d < 30
          ? `${d} days ago`
          : `${Math.floor(d / 30)} mo ago`,
  ru: (d) =>
    d === 0
      ? 'сегодня'
      : d === 1
        ? '1 день назад'
        : d < 5
          ? `${d} дня назад`
          : d < 30
            ? `${d} дней назад`
            : `${Math.floor(d / 30)} мес. назад`,
};
